// Usage: dotnet run --file GenerateFlow.cs -- <FlowSolutionPath> <FlowName> <CodeAppPath>
// Example: dotnet run --file GenerateFlow.cs -- "C:\...\Solutions.Logic" "contoso_myflow" "C:\...\Apps.MyApp"
// Produces the same files 'pa app add flow' writes, but from the flow definition in solution source.

#:property Nullable=disable

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;
using System.Xml.Linq;

const string LogicFlowsApiId = "/providers/Microsoft.PowerApps/apis/shared_logicflows";
const string ApiVersion = "2015-02-01-preview";
const string Header = "/*!\n * Copyright (C) Microsoft Corporation. All rights reserved.\n * This file is autogenerated. Do not edit this file directly.\n */\n";

if (args.Length < 3)
{
    Console.Error.WriteLine("Usage: dotnet run --file GenerateFlow.cs -- <FlowSolutionPath> <FlowName> <CodeAppPath>");
    return 1;
}

var solutionPath = args[0];
var flowName = args[1];
var appPath = args[2];

var jsonOptions = new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

// ── Locate flow definition ────────────────────────────────────────────────────
// Searched recursively, so it works whatever SolutionRootPath the solution project uses.
var flowJsonPath = Directory.Exists(solutionPath)
    ? Directory.GetFiles(solutionPath, $"{flowName}-*.json", SearchOption.AllDirectories)
        .FirstOrDefault(f => Path.GetFileName(Path.GetDirectoryName(f)) == "Workflows"
            && !f.Split(Path.DirectorySeparatorChar).Any(p => p is "bin" or "obj"))
    : null;
if (flowJsonPath is null)
{
    Console.Error.WriteLine($"Flow definition 'Workflows/{flowName}-<GUID>.json' not found under {solutionPath}");
    return 1;
}

var dataXmlPath = flowJsonPath + ".data.xml";
if (!File.Exists(dataXmlPath))
{
    Console.Error.WriteLine($"Flow metadata not found: {dataXmlPath}");
    return 1;
}

var workflowXml = XDocument.Load(dataXmlPath).Root;
var workflowId = workflowXml.Attribute("WorkflowId")?.Value.Trim('{', '}').ToLowerInvariant();
var displayName = workflowXml.Attribute("Name")?.Value ?? flowName;
if (string.IsNullOrEmpty(workflowId))
{
    Console.Error.WriteLine($"WorkflowId missing in {dataXmlPath}");
    return 1;
}

var flow = JsonNode.Parse(File.ReadAllText(flowJsonPath));
var definition = flow["properties"]?["definition"];

var trigger = (definition?["triggers"] as JsonObject)?
    .FirstOrDefault(t => (string)t.Value?["kind"] == "PowerAppV2");
if (trigger is null || trigger.Value.Value is null)
{
    Console.Error.WriteLine($"Flow '{displayName}' has no Power Apps (V2) trigger. Only flows with a PowerAppV2 trigger can be called from a code app.");
    return 1;
}

var invokerConnections = (flow["properties"]?["connectionReferences"] as JsonObject)?
    .Where(c => string.Equals((string)c.Value?["runtimeSource"], "invoker", StringComparison.OrdinalIgnoreCase))
    .Select(c => c.Key)
    .ToList() ?? new List<string>();
if (invokerConnections.Count > 0)
    Console.WriteLine($"Warning: run-only user connections ({string.Join(", ", invokerConnections)}) are not wired into power.config.json dependencies.");

var inputSchema = trigger.Value.Value["inputs"]?["schema"]?.DeepClone() as JsonObject
    ?? new JsonObject { ["type"] = "object", ["properties"] = new JsonObject(), ["required"] = new JsonArray() };
var responseSchema = FindResponseSchema(definition?["actions"] as JsonObject);

// ── Names, same rules as the pa CLI codegen ───────────────────────────────────
var schemaName = ToIdentifier(displayName, stripWhitespace: true);
var modelName = char.ToUpperInvariant(schemaName[0]) + schemaName.Substring(1);

// ── power.config.json ─────────────────────────────────────────────────────────
var powerConfigPath = Path.Combine(appPath, "power.config.json");
if (!File.Exists(powerConfigPath))
{
    Console.Error.WriteLine($"File not found: {powerConfigPath}");
    return 1;
}

var powerConfig = JsonNode.Parse(File.ReadAllText(powerConfigPath)).AsObject();
if (powerConfig["connectionReferences"] is not JsonObject connectionReferences)
{
    connectionReferences = new JsonObject();
    powerConfig["connectionReferences"] = connectionReferences;
}

var referenceKey = connectionReferences
    .FirstOrDefault(r => string.Equals((string)r.Value?["workflowDetails"]?["workflowEntityId"], workflowId, StringComparison.OrdinalIgnoreCase))
    .Key ?? Guid.NewGuid().ToString();

var takenDataSources = connectionReferences
    .Where(r => r.Key != referenceKey)
    .SelectMany(r => (r.Value?["dataSources"] as JsonArray)?.Select(d => ((string)d).ToLowerInvariant()) ?? Enumerable.Empty<string>())
    .ToHashSet();
var dataSourceName = schemaName.ToLowerInvariant();
for (var i = 1; takenDataSources.Contains(dataSourceName); i++) dataSourceName = $"{schemaName.ToLowerInvariant()}_{i}";

// workflowName is the Power Automate flow id, which only exists in an environment; the workflow id stands in for it offline.
connectionReferences[referenceKey] = new JsonObject
{
    ["id"] = LogicFlowsApiId,
    ["displayName"] = "Logic flows",
    ["dataSources"] = new JsonArray(dataSourceName),
    ["workflowDetails"] = new JsonObject
    {
        ["workflowEntityId"] = workflowId,
        ["workflowDisplayName"] = displayName,
        ["workflowName"] = workflowId,
    },
};
WriteText(powerConfigPath, powerConfig.ToJsonString(jsonOptions) + "\n");
Console.WriteLine($"power.config.json: logic flow '{dataSourceName}'");

// ── .power/schemas/logicflows/<name>.Schema.json ──────────────────────────────
var triggerName = trigger.Value.Key;
var runPath = $"/{{connectionId}}/triggers/{triggerName}/run";

var definitions = new JsonObject { ["ManualTriggerInput"] = inputSchema };
var responses = new JsonObject();
if (responseSchema is not null)
{
    definitions["ResponseActionOutput"] = responseSchema;
    responses["200"] = new JsonObject { ["description"] = "Ok", ["schema"] = new JsonObject { ["$ref"] = "#/definitions/ResponseActionOutput" } };
    responses["default"] = new JsonObject { ["description"] = "The Flow Response.", ["schema"] = new JsonObject { ["type"] = "object" } };
}
else
{
    responses["202"] = new JsonObject { ["description"] = "Accepted" };
}

var schema = new JsonObject
{
    ["name"] = displayName,
    ["id"] = LogicFlowsApiId,
    ["type"] = "Microsoft.PowerApps/apis",
    ["properties"] = new JsonObject
    {
        ["displayName"] = displayName,
        ["isCustom"] = false,
        ["swagger"] = new JsonObject
        {
            ["swagger"] = "2.0",
            ["info"] = new JsonObject { ["title"] = displayName, ["version"] = ApiVersion },
            ["schemes"] = new JsonArray("https"),
            ["consumes"] = new JsonArray("application/json"),
            ["produces"] = new JsonArray("application/json"),
            ["paths"] = new JsonObject
            {
                [runPath] = new JsonObject
                {
                    ["post"] = new JsonObject
                    {
                        ["operationId"] = "Run",
                        ["description"] = "Runs a logic flow trigger.",
                        ["parameters"] = new JsonArray(
                            new JsonObject { ["name"] = "connectionId", ["in"] = "path", ["required"] = true, ["type"] = "string", ["x-ms-visibility"] = "internal" },
                            new JsonObject { ["name"] = "input", ["description"] = "The trigger's input", ["in"] = "body", ["required"] = true, ["schema"] = new JsonObject { ["$ref"] = "#/definitions/ManualTriggerInput" } },
                            new JsonObject { ["name"] = "api-version", ["description"] = "The api version", ["in"] = "query", ["required"] = true, ["default"] = ApiVersion, ["x-ms-visibility"] = "internal", ["type"] = "string" }),
                        ["responses"] = responses,
                    },
                },
            },
            ["definitions"] = definitions,
            ["basePath"] = "/apim/logicflows",
        },
    },
};
var logicFlowsSchemaPath = Path.Combine(appPath, ".power", "schemas", "logicflows", $"{schemaName}.Schema.json");
WriteText(logicFlowsSchemaPath, schema.ToJsonString(jsonOptions));
Console.WriteLine($"Schema: {Path.GetRelativePath(appPath, logicFlowsSchemaPath)}");

// ── .power/schemas/appschemas/dataSourcesInfo.ts ──────────────────────────────
var dataSourcesInfoPath = Path.Combine(appPath, ".power", "schemas", "appschemas", "dataSourcesInfo.ts");
var dataSourcesInfo = new JsonObject();
if (File.Exists(dataSourcesInfoPath))
{
    var text = File.ReadAllText(dataSourcesInfoPath);
    var start = text.IndexOf('{', text.IndexOf("dataSourcesInfo", StringComparison.Ordinal));
    var end = text.LastIndexOf('}');
    dataSourcesInfo = JsonNode.Parse(text.Substring(start, end - start + 1)).AsObject();
}

var responseInfo = new JsonObject();
if (responseSchema is not null)
{
    responseInfo["200"] = new JsonObject { ["type"] = "object" };
    responseInfo["default"] = new JsonObject { ["type"] = "object" };
}
else
{
    responseInfo["202"] = new JsonObject { ["type"] = "void" };
}

dataSourcesInfo[dataSourceName] = new JsonObject
{
    ["tableId"] = "",
    ["version"] = "",
    ["primaryKey"] = "",
    ["dataSourceType"] = "Connector",
    ["apis"] = new JsonObject
    {
        ["Run"] = new JsonObject
        {
            ["path"] = runPath,
            ["method"] = "POST",
            ["parameters"] = new JsonArray(
                new JsonObject { ["name"] = "connectionId", ["in"] = "path", ["required"] = true, ["type"] = "string" },
                new JsonObject { ["name"] = "input", ["in"] = "body", ["required"] = true, ["type"] = "object" },
                new JsonObject { ["name"] = "api-version", ["in"] = "query", ["required"] = true, ["type"] = "string" }),
            ["responseInfo"] = responseInfo,
        },
    },
};
WriteText(dataSourcesInfoPath,
    "/*!\n * Copyright (C) Microsoft Corporation. All rights reserved.\n * This file is auto-generated. Do not modify it manually.\n * Changes to this file may be overwritten.\n */\n\n" +
    $"export const dataSourcesInfo = {dataSourcesInfo.ToJsonString(jsonOptions)};\n");
Console.WriteLine($"dataSourcesInfo.ts: '{dataSourceName}'");

// ── src/generated/models + services ───────────────────────────────────────────
var generatedPath = Path.Combine(appPath, "src", "generated");

var model = new StringBuilder(Header);
model.Append('\n');
model.Append(RenderInterface("ManualTriggerInput", inputSchema));
if (responseSchema is not null)
{
    model.Append('\n');
    model.Append(RenderInterface("ResponseActionOutput", responseSchema));
}
WriteText(Path.Combine(generatedPath, "models", $"{modelName}Model.ts"), model.ToString());

var outputType = responseSchema is not null ? "ResponseActionOutput" : "void";
var service = new StringBuilder(Header);
service.Append('\n');
service.Append("import type { IOperationResult } from '@microsoft/power-apps/data';\n");
service.Append($"import type {{ ManualTriggerInput }} from '../models/{modelName}Model';\n");
if (responseSchema is not null) service.Append($"import type {{ ResponseActionOutput }} from '../models/{modelName}Model';\n");
service.Append("import { dataSourcesInfo } from '../../../.power/schemas/appschemas/dataSourcesInfo';\n");
service.Append("import { getClient } from '@microsoft/power-apps/data';\n");
service.Append('\n');
service.Append($"export class {modelName}Service {{\n");
service.Append($"  private static readonly dataSourceName = '{dataSourceName}';\n");
service.Append('\n');
service.Append("  private static readonly client = getClient(dataSourcesInfo);\n");
service.Append('\n');
service.Append($"  public static async Run(input: ManualTriggerInput): Promise<IOperationResult<{outputType}>> {{\n");
service.Append("    const params: { input: ManualTriggerInput } = { input };\n");
service.Append($"    const allParams = {{ ...params, \"api-version\": \"{ApiVersion}\" }};\n");
service.Append($"    const result = await {modelName}Service.client.executeAsync<{{ input: ManualTriggerInput }}, {outputType}>(\n");
service.Append("      {\n");
service.Append("        connectorOperation: {\n");
service.Append($"          tableName: {modelName}Service.dataSourceName,\n");
service.Append("          operationName: 'Run',\n");
service.Append("          parameters: allParams\n");
service.Append("        },\n");
service.Append("      });\n");
service.Append("    return result;\n");
service.Append("  }\n");
service.Append("}\n");
WriteText(Path.Combine(generatedPath, "services", $"{modelName}Service.ts"), service.ToString());
Console.WriteLine($"Generated {modelName}Model.ts and {modelName}Service.ts");

var indexPath = Path.Combine(generatedPath, "index.ts");
var indexLines = File.ReadAllLines(indexPath).ToList();
InsertExport(indexLines, "// Models", $"export * as {modelName}Model from './models/{modelName}Model';");
InsertExport(indexLines, "// Services", $"export * from './services/{modelName}Service';");
WriteText(indexPath, string.Join("\n", indexLines) + "\n");

return 0;

// ── Helpers ───────────────────────────────────────────────────────────────────
static JsonObject FindResponseSchema(JsonObject actions)
{
    if (actions is null) return null;
    foreach (var (_, action) in actions)
    {
        if (action is not JsonObject a) continue;
        if ((string)a["type"] == "Response" && (string)a["kind"] == "PowerApp" && a["inputs"]?["schema"] is JsonObject s) return (JsonObject)s.DeepClone();

        var nested = new[] { a["actions"], a["else"]?["actions"], a["default"]?["actions"] }
            .Concat((a["cases"] as JsonObject)?.Select(c => c.Value?["actions"]) ?? Enumerable.Empty<JsonNode>());
        foreach (var n in nested)
        {
            var found = FindResponseSchema(n as JsonObject);
            if (found is not null) return found;
        }
    }
    return null;
}

static string ToIdentifier(string value, bool stripWhitespace)
{
    var result = value.Trim();
    if (stripWhitespace) result = Regex.Replace(result, @"\s", "");
    result = Regex.Replace(result, @"[^a-zA-Z0-9_$]", "_");
    if (result.Length > 0 && char.IsDigit(result[0])) result = "_" + result;
    return result;
}

static string RenderInterface(string name, JsonObject schema)
{
    var properties = schema["properties"] as JsonObject;
    if (properties is null || properties.Count == 0) return $"export type {name} = object;\n";

    var required = (schema["required"] as JsonArray)?.Select(r => (string)r).ToHashSet() ?? new HashSet<string>();
    var sb = new StringBuilder($"export interface {name} {{\n");
    foreach (var (propName, prop) in properties)
    {
        if (prop?["description"] is JsonValue description)
        {
            foreach (var line in ((string)description).Split('\n')) sb.Append($"  // {line.TrimEnd('\r')}\n");
        }

        var identifier = ToIdentifier(propName, stripWhitespace: false);
        var key = identifier == propName ? propName : $"'{propName.Replace("'", "\\'")}'";
        var optional = required.Contains(propName) ? "" : "?";
        sb.Append($"  {key}{optional}: {TsType(prop)};\n");
    }
    sb.Append("}\n");
    return sb.ToString();
}

static string TsType(JsonNode prop)
{
    if (prop?["enum"] is JsonArray values && values.Count > 0)
        return string.Join(" | ", values.Select(v => $"'{v?.ToString().Replace("\\", "\\\\").Replace("'", "\\'")}'"));

    return (string)prop?["type"] switch
    {
        "string" => "string",
        "number" or "integer" => "number",
        "boolean" => "boolean",
        "object" => "Record<string, unknown>",
        _ => "unknown",
    };
}

static void InsertExport(List<string> lines, string section, string export)
{
    if (lines.Contains(export)) return;
    var sectionIndex = lines.FindIndex(l => l.Contains(section));
    if (sectionIndex < 0)
    {
        lines.Add(export);
        return;
    }
    var insertIndex = lines.FindIndex(sectionIndex + 1, l => l.Trim() == "");
    lines.Insert(insertIndex < 0 ? lines.Count : insertIndex, export);
}

static void WriteText(string path, string content)
{
    Directory.CreateDirectory(Path.GetDirectoryName(path));
    File.WriteAllText(path, content.Replace("\r\n", "\n"));
}
